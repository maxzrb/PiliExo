/// 返回新增的键数量；已有值保持不变。
int applyMissingDefaultValues(
  Map<String, Object?> defaults, {
  required bool Function(String key) containsKey,
  required void Function(String key, Object? value) setValue,
}) {
  var added = 0;
  for (final entry in defaults.entries) {
    if (containsKey(entry.key)) continue;
    setValue(entry.key, entry.value);
    added++;
  }
  return added;
}
